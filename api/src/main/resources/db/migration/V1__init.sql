CREATE TABLE project (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name        TEXT        NOT NULL,
                         slug        TEXT        NOT NULL UNIQUE,
                         created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE api_key (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         project_id  BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
                         key_hash    TEXT        NOT NULL UNIQUE,
                         label       TEXT        NOT NULL,
                         created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
                         revoked_at  TIMESTAMPTZ
);

CREATE TABLE ci_run (
                        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        project_id       BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
                        provider_run_id  TEXT        NOT NULL,
                        run_attempt      INT         NOT NULL,
                        commit_sha       TEXT        NOT NULL,
                        branch           TEXT        NOT NULL,
                        started_at       TIMESTAMPTZ NOT NULL,
                        total            INT         NOT NULL,
                        failed           INT         NOT NULL,
                        UNIQUE (project_id, provider_run_id, run_attempt)
);

CREATE TABLE test_case (
                           id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           project_id  BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
                           suite       TEXT   NOT NULL,
                           name        TEXT   NOT NULL,
                           UNIQUE (project_id, suite, name)
);

CREATE TABLE test_result (
                             id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             ci_run_id        BIGINT NOT NULL REFERENCES ci_run (id) ON DELETE CASCADE,
                             test_case_id     BIGINT NOT NULL REFERENCES test_case (id) ON DELETE CASCADE,
                             status           TEXT   NOT NULL CHECK (status IN ('PASSED', 'FAILED', 'ERROR', 'SKIPPED')),
                             duration_ms      INT    NOT NULL,
                             failure_message  TEXT
);

CREATE INDEX idx_test_result_test_case ON test_result (test_case_id);
CREATE INDEX idx_test_result_ci_run    ON test_result (ci_run_id);
CREATE INDEX idx_ci_run_commit         ON ci_run (project_id, commit_sha);